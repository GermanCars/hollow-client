package dev.hollow.mixin;

import dev.hollow.Hollow;
import io.netty.channel.ChannelFutureListener;
import io.netty.channel.ChannelHandlerContext;
import net.minecraft.network.Connection;
import net.minecraft.network.protocol.Packet;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(Connection.class)
abstract class ConnectionMixin {
    @Inject(method = "channelRead0(Lio/netty/channel/ChannelHandlerContext;Lnet/minecraft/network/protocol/Packet;)V", at = @At("HEAD"), cancellable = true)
    private void hollow$receive(ChannelHandlerContext ctx, Packet<?> packet, CallbackInfo ci) { if (Hollow.received((Connection) (Object) this, packet)) ci.cancel(); }

    @Inject(method = "send(Lnet/minecraft/network/protocol/Packet;Lio/netty/channel/ChannelFutureListener;Z)V", at = @At("HEAD"), cancellable = true)
    private void hollow$send(Packet<?> packet, ChannelFutureListener listener, boolean flush, CallbackInfo ci) { if (Hollow.sending((Connection) (Object) this, packet)) ci.cancel(); }
}
